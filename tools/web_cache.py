"""Content-address web resources independently of the surrounding release."""

import hashlib
import json
import re


def version_distribution(dist, worker):
    files = {
        path.name: path
        for path in dist.iterdir()
        if path.is_file() and path.name not in {"sw.js", "version.json"}
    }
    versions = {}
    visiting = set()
    text_files = {"index.html", "style.css", "loading-layout.css", "app.js", "manifest.webmanifest"}

    def version(name):
        if name in versions:
            return versions[name]
        if name in visiting:
            raise ValueError(f"Circular web resource reference: {name}")
        visiting.add(name)
        path = files[name]
        if name in text_files:
            content = path.read_text()
            if "__ASSET_VERSIONS__" in content:
                content = content.replace(
                    "__ASSET_VERSIONS__",
                    json.dumps(
                        {key: version(key) for key in sorted(files) if key not in text_files}
                    ),
                )
            content = re.sub(
                r"([\w.-]+)\?v=__WEB_BUILD__",
                lambda match: f"{match[1]}?v={version(match[1])}",
                content,
            )
            if "__WEB_BUILD__" in content:
                raise ValueError(f"Unresolved web resource reference: {name}")
            path.write_text(content)
        with path.open("rb") as stream:
            versions[name] = hashlib.file_digest(stream, "sha256").hexdigest()[:20]
        visiting.remove(name)
        return versions[name]

    for name in sorted(files):
        version(name)
    tag = hashlib.sha256((worker + json.dumps(versions, sort_keys=True)).encode()).hexdigest()[:20]
    # This small, uncached probe describes the whole release, without making its
    # own generated bytes part of the hash (or the offline asset package).
    (dist / "version.json").write_text(json.dumps({"build": tag}) + "\n")
    precache = ["./", *[f"{name}?v={versions[name]}" for name in sorted(files)]]
    (dist / "sw.js").write_text(
        worker.replace("__BUILD_HASH__", tag).replace("__PRECACHE_FILES__", json.dumps(precache))
    )
    return versions
